func subdivisionSet(blob string) map[string]map[string]struct{} {
	subdivisions := make(map[string]map[string]struct{})
	for _, line := range strings.Split(blob, "\n") {
		fields := strings.Fields(line)
		if len(fields) == 0 {
			continue
		}
		codes := make(map[string]struct{}, len(fields)-1)
		for _, code := range fields[1:] {
			codes[code] = struct{}{}
		}
		subdivisions[fields[0]] = codes
	}
	return subdivisions
}
