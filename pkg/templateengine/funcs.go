// Funcs returns the sprout functions available to Credimi templates.
//
// It is sprout's "all" group without the env registry: templates can reach
// tenant-controlled input, and env/expandEnv would expose the process
// environment (server secrets) to whoever writes the template.
func Funcs() template.FuncMap {
	return sprout.New(sprout.WithRegistries(
		checksum.NewRegistry(),
		conversion.NewRegistry(),
		encoding.NewRegistry(),
		filesystem.NewRegistry(),
		maps.NewRegistry(),
		network.NewRegistry(),
		numeric.NewRegistry(),
		random.NewRegistry(),
		reflect.NewRegistry(),
		regexp.NewRegistry(),
		semver.NewRegistry(),
		slices.NewRegistry(),
		std.NewRegistry(),
		strings.NewRegistry(),
		time.NewRegistry(),
		uniqueid.NewRegistry(),
	)).Build()
}
